    const baseImagePart = dataUrlToPart(baseImageUrl);
    const prompt = `You are an expert fashion photo editor. Your task is to change the pose of the person in the image to '${pose}'. You MUST NOT change the person's identity, their clothing, or the background. The final image should be photorealistic and seamlessly edited. Return ONLY the final image.`;
    
